-- Migração inicial do esquema relacional em nuvem (Supabase Postgres)
-- Baseado em docs/spec.md e nos ADRs 0001 a 0005.
-- Prefixo quiz_ para isolamento em projeto Supabase compartilhado.

-- Perfis autenticados da equipe (Administrador e Operador) vinculados ao auth.users
CREATE TABLE IF NOT EXISTS quiz_profiles (
  id uuid PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  name text NOT NULL,
  email text NOT NULL UNIQUE,
  role text NOT NULL CHECK (role IN ('admin', 'operator')),
  created_at timestamptz NOT NULL DEFAULT now()
);

-- Banco de Questões central e reutilizável entre Eventos
CREATE TABLE IF NOT EXISTS quiz_questions (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  text text NOT NULL,
  options jsonb NOT NULL CHECK (jsonb_typeof(options) = 'array' AND jsonb_array_length(options) = 4),
  correct_index smallint NOT NULL CHECK (correct_index BETWEEN 0 AND 3),
  difficulty text NOT NULL CHECK (difficulty IN ('facil', 'moderado', 'dificil')),
  tags text[] NOT NULL DEFAULT '{}',
  is_disabled boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

-- Eventos independentes (feiras, congressos, ações promocionais)
CREATE TABLE IF NOT EXISTS quiz_events (
  id uuid PRIMARY KEY,
  name text NOT NULL,
  slug text NOT NULL UNIQUE,
  start_time timestamptz,
  end_time timestamptz,
  enable_out_of_period_message boolean NOT NULL DEFAULT false,
  is_active boolean NOT NULL DEFAULT true,
  settings jsonb NOT NULL DEFAULT '{}'::jsonb,
  prize_stock_remaining integer,
  customizations jsonb NOT NULL DEFAULT '{}'::jsonb,
  config_version integer NOT NULL DEFAULT 1,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

-- Relação N:N opcional entre Eventos e Questões selecionadas
CREATE TABLE IF NOT EXISTS quiz_event_questions (
  event_id uuid NOT NULL REFERENCES quiz_events(id) ON DELETE CASCADE,
  question_id bigint NOT NULL REFERENCES quiz_questions(id) ON DELETE CASCADE,
  PRIMARY KEY (event_id, question_id)
);

-- Totens pareados ao painel administrativo e vinculados a um Evento
CREATE TABLE IF NOT EXISTS quiz_totems (
  id uuid PRIMARY KEY,
  name text NOT NULL,
  pairing_code text NOT NULL UNIQUE,
  device_token text NOT NULL UNIQUE,
  event_id uuid REFERENCES quiz_events(id) ON DELETE SET NULL,
  pin_code text NOT NULL DEFAULT '0000',
  last_seen_at timestamptz,
  online_status text NOT NULL DEFAULT 'offline',
  current_screen text NOT NULL DEFAULT 'initial',
  pending_sync_count integer NOT NULL DEFAULT 0,
  created_at timestamptz NOT NULL DEFAULT now()
);

-- Partidas concluídas pelos Participantes (id gerado no Totem como chave de idempotência)
CREATE TABLE IF NOT EXISTS quiz_matches (
  id uuid PRIMARY KEY,
  event_id uuid NOT NULL REFERENCES quiz_events(id) ON DELETE CASCADE,
  totem_id uuid REFERENCES quiz_totems(id) ON DELETE SET NULL,
  participant_name text NOT NULL,
  participant_phone text NOT NULL,
  score integer NOT NULL CHECK (score >= 0),
  total_questions integer NOT NULL CHECK (total_questions > 0),
  time_seconds integer NOT NULL CHECK (time_seconds >= 0),
  answers jsonb NOT NULL DEFAULT '[]'::jsonb,
  played_at timestamptz NOT NULL,
  synced_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_quiz_matches_event_ranking
  ON quiz_matches (event_id, score DESC, time_seconds ASC);

CREATE INDEX IF NOT EXISTS idx_quiz_matches_event_phone
  ON quiz_matches (event_id, participant_phone);

-- Brindes e Trava de Brinde por Evento e telefone
CREATE TABLE IF NOT EXISTS quiz_prize_claims (
  id uuid PRIMARY KEY,
  event_id uuid NOT NULL REFERENCES quiz_events(id) ON DELETE CASCADE,
  match_id uuid NOT NULL REFERENCES quiz_matches(id) ON DELETE CASCADE,
  totem_id uuid REFERENCES quiz_totems(id) ON DELETE SET NULL,
  participant_name text NOT NULL,
  participant_phone text NOT NULL,
  status text NOT NULL CHECK (
    status IN ('awaiting_pickup', 'delivered', 'revoked', 'offline_duplicate_conflict')
  ),
  delivered_at timestamptz,
  delivered_by uuid REFERENCES quiz_profiles(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

-- Garante apenas 1 Brinde ativo por telefone em cada Evento, isolando conflitos offline
CREATE UNIQUE INDEX IF NOT EXISTS idx_quiz_prize_claims_unique_active_per_event_phone
  ON quiz_prize_claims (event_id, participant_phone)
  WHERE status IN ('awaiting_pickup', 'delivered');

-- Bloqueios por Desistência temporários por telefone no Evento
CREATE TABLE IF NOT EXISTS quiz_give_up_lockouts (
  id uuid PRIMARY KEY,
  event_id uuid NOT NULL REFERENCES quiz_events(id) ON DELETE CASCADE,
  totem_id uuid REFERENCES quiz_totems(id) ON DELETE SET NULL,
  participant_phone text NOT NULL,
  locked_at timestamptz NOT NULL,
  expires_at timestamptz NOT NULL,
  unlocked_by uuid REFERENCES quiz_profiles(id) ON DELETE SET NULL
);

CREATE INDEX IF NOT EXISTS idx_quiz_give_up_lockouts_event_phone_expires
  ON quiz_give_up_lockouts (event_id, participant_phone, expires_at DESC);

